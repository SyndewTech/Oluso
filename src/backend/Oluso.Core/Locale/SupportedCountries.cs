namespace Oluso.Core.Locale;

/// <summary>
/// One country or territory the platform can address or dial.
/// </summary>
/// <param name="Code">ISO 3166-1 alpha-2 code.</param>
/// <param name="Name">English display name.</param>
/// <param name="DialCode">International calling code without the leading "+".</param>
public record CountryInfo(string Code, string Name, string DialCode)
{
    /// <summary>Flag emoji built from the regional indicator letters of the code.</summary>
    public string Flag => string.Concat(Code.ToUpperInvariant().Select(c => char.ConvertFromUtf32(0x1F1E6 + (c - 'A'))));
}

