    private static readonly Dictionary<string, CountryInfo> ByCode =
        All.ToDictionary(c => c.Code, StringComparer.OrdinalIgnoreCase);

    public static CountryInfo? GetByCode(string? code) =>
        !string.IsNullOrWhiteSpace(code) && ByCode.TryGetValue(code.Trim(), out var country) ? country : null;

    /// <summary>
    /// The country a culture name points at, e.g. "en-NG" → Nigeria. Null when the
    /// culture has no region part or the region is unknown.
    /// </summary>
    public static CountryInfo? FromCulture(string? cultureName)
    {
        if (string.IsNullOrWhiteSpace(cultureName)) return null;
        var parts = cultureName.Split('-', '_');
        return parts.Length >= 2 ? GetByCode(parts[^1]) : null;
    }
